// The one thing about a PingAM script the type system cannot enforce.
//
// `defineAmScript` narrows `main`'s parameter to the declared outcomes, so
// `action.goTo("hihg")` is a compile error. An author can hand that back by
// annotating the parameter:
//
//   main: (action: { goTo(outcome: string): void }) => { ... }
//
// and TypeScript accepts it, because it compares METHOD parameters bivariantly
// even under `strictFunctionTypes` -- and the bivariance comes from the
// annotation's own method declaration, so nothing done to `AmAction` can stop
// it. Making `goTo` a function-typed property was tried and changes nothing;
// only replacing `action` with a bare callback would close it by type, at the
// cost of no longer mirroring the `action.goTo(...)` PingAM actually puts in
// scope.
//
// So it is closed from the source side instead: inside a `defineAmScript`
// call, `main`'s parameters carry no type annotation. Inference is the whole
// mechanism, and there is no legitimate reason to override it.
//
// Managed file - regenerated by `fo upgrade`.

import { readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Every annotated `main` parameter in a `defineAmScript` call.
 *
 * Syntactic on purpose: it runs on the same files `tsconfig.am.json` compiles,
 * but it needs no checker and no program, so it cannot be defeated by the same
 * widening it exists to catch.
 */
export function findAnnotatedActionParameters(fileNames) {
  const findings = [];

  for (const fileName of fileNames) {
    const sourceFile = ts.createSourceFile(
      fileName,
      readFileSync(fileName, "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );

    const visit = (node) => {
      if (
        ts.isCallExpression(node) &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === "defineAmScript" &&
        node.arguments.length > 0 &&
        node.arguments[0] !== undefined &&
        ts.isObjectLiteralExpression(node.arguments[0])
      ) {
        for (const property of node.arguments[0].properties) {
          if (!ts.isPropertyAssignment(property)) continue;
          if (!ts.isIdentifier(property.name)) continue;
          if (property.name.text !== "main") continue;
          const fn = property.initializer;
          if (!ts.isArrowFunction(fn) && !ts.isFunctionExpression(fn)) continue;
          for (const parameter of fn.parameters) {
            if (parameter.type === undefined) continue;
            const { line, character } = sourceFile.getLineAndCharacterOfPosition(
              parameter.getStart(sourceFile),
            );
            findings.push({
              file: relative(projectRoot, fileName),
              line: line + 1,
              column: character + 1,
              text: parameter.getText(sourceFile),
            });
          }
        }
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(sourceFile, visit);
  }

  return findings;
}

/**
 * The authored PingAM scripts.
 *
 * Derived from `tsconfig.am.json` rather than by globbing, so the rule cannot
 * drift from the program, but narrowed to `src/scripts/` -- the framework's own
 * files and `tests/am-typing.ts` are not authored scripts, and am-typing.ts
 * deliberately contains an annotated parameter as a compile-time negative test.
 */
function amScriptFiles() {
  const configPath = join(projectRoot, "tsconfig.am.json");
  const read = ts.readConfigFile(configPath, (p) => readFileSync(p, "utf8"));
  if (read.error) {
    throw new Error(
      `tsconfig.am.json: ${ts.flattenDiagnosticMessageText(read.error.messageText, " ")}`,
    );
  }
  const parsed = ts.parseJsonConfigFileContent(
    read.config,
    ts.sys,
    dirname(configPath),
  );
  if (parsed.fileNames.length === 0) {
    throw new Error("tsconfig.am.json: matched no files");
  }
  const scriptsDir = join(projectRoot, "src", "scripts") + "/";
  return parsed.fileNames.filter(
    (f) => f.startsWith(scriptsDir) && !f.endsWith(".d.ts"),
  );
}

/**
 * Throw if any PingAM script annotates `main`'s parameter.
 *
 * Called from the type-check step of `tools/build.mjs`, before emission, for
 * the same reason the engine-usage check is: a rule that fires after the
 * artefact is written is not a rule.
 */
export function assertNoAnnotatedActionParameters() {
  const findings = findAnnotatedActionParameters(amScriptFiles());
  if (findings.length === 0) return;
  throw new Error(
    "a PingAM script annotated `main`'s parameter:\n" +
      findings
        .map(
          (f) =>
            `  ${f.file}:${f.line}:${f.column}  \`${f.text}\`\n` +
            "    Let it be inferred. An explicit annotation replaces the " +
            "outcome-narrowed\n    type, and `goTo` silently goes back to " +
            "accepting any string.",
        )
        .join("\n"),
  );
}
