/** One amster `Scripts` entity per AM script, ready for `fo amster`. */
function amScriptOutputs(built) {
  return built.map((script) => ({
    path: join(amScriptsDir, script.name + ".json"),
    content:
      JSON.stringify(
        {
          metadata: {
            realm: "/",
            amsterVersion: "&{version}",
            entityType: "Scripts",
            entityId: scriptUuid(script.name),
            pathParams: {},
          },
          data: {
            _id: scriptUuid(script.name),
            name: script.definition.name,
            description:
              script.definition.description ??
              "Generated by fo build from " + script.sourceRelative,
            // AM stores the body base64-encoded.
            script: Buffer.from(script.code, "utf8").toString("base64"),
            language: "JAVASCRIPT",
            context: script.definition.context,
            evaluatorVersion: "2.0",
          },
        },
        null,
        2
      ) + "\n",
  }));
}

