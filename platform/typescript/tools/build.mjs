/**
 * Every TypeScript program in this package.
 *
 * THE list, not a copy of it: `package.json`'s `type-check` script runs this
 * file too (`--type-check-only`), because when the two kept their own copies
 * they drifted - `tsconfig.am.json` was in one and not the other, so a type
 * error in a PingAM script passed `fo build`, was emitted, and only `fo check`
 * would catch it. A build that emits code it never type-checked is not a
 * build.
 */
const TYPE_CHECK_PROGRAMS = [
  "tsconfig.json",
  "tsconfig.am.json",
  "tsconfig.tests.json",
];

function typeCheck() {
  // tsgo, not tsc: the project moved to TypeScript 7 for the 5.7x, and this
  // file was left behind on the old compiler while `package.json` moved. Two
  // programs AND two compilers out of step.
  const tsgo = join(projectRoot, "node_modules", ".bin", "tsgo");
  if (!existsSync(tsgo)) {
    // Never "run npm install": the dependency tree is built by nix from the
    // committed lockfile and linked in by the devShell.
    throw new Error(
      "node_modules is missing. Enter the dev shell (direnv allow, or " +
        "nix develop) — it links platform/typescript/node_modules from the " +
        "nix store. `npm install` is never the answer here."
    );
  }
  for (const config of TYPE_CHECK_PROGRAMS) {
    const result = spawnSync(
      tsgo,
      ["--noEmit", "-p", join(projectRoot, config)],
      {
        stdio: "inherit",
        cwd: projectRoot,
      }
    );
    if (result.status !== 0) {
      throw new Error("type-check failed (" + config + ")");
    }
  }

  // Part of the type-check, not a separate step, and deliberately BEFORE any
  // emission: `@babel/preset-env` runs with `useBuiltIns: false`, so a builtin
  // Rhino lacks is not polyfilled -- it type-checks, builds, deploys, and
  // throws inside somebody's login. tsgo cannot see that, because the pinned
  // `lib` legitimately declares those members and TypeScript has no way to
  // un-declare one.
  // FIRST, because the two checks below read `engine-surface.json` and are
  // only worth anything if it still describes the compilers in use. After a
  // bump, a newly declared builtin is simply absent from the file rather than
  // recorded `false`, and an absent key reads as "fine".
  assertMeasurementCovers(
    JSON.parse(readFileSync(join(projectRoot, "framework", "engine-surface.json"), "utf8")),
    JSON.parse(readFileSync(join(projectRoot, "framework", "engine-coverage.json"), "utf8")),
  );

  assertNoAbsentBuiltinUses();

  // Same step, same reason: `_wrapNativeSuper` was measured to break on both
  // engines, and a syntactic rule could not tell a real `Map` from a project
  // class that happens to be called one.
  assertNoNativeSubclasses();
}

function entryPoints() {
  if (!existsSync(endpointsDir)) {
    return [];
  }
  return readdirSync(endpointsDir)
    .filter((name) => name.endsWith(".ts") && !name.endsWith(".d.ts"))
    .sort()
    .map((name) => join(endpointsDir, name));
}

/**
 * A stable UUID for an amster Scripts entity, derived from the script name.
 *
 * AM identifies scripts by UUID, but a developer names a FILE. Deriving the id
 * means renaming nothing and re-importing repeatedly both stay idempotent -- a
 * random id would create a second copy of the script on every build.
 */
function scriptUuid(name) {
  const hash = createHash("sha1")
    .update("fo/am-script/" + name)
    .digest("hex");
  const hex = hash.slice(0, 32).split("");
  // Stamp version 5 and the RFC 4122 variant so AM sees a well-formed UUID.
  hex[12] = "5";
  hex[16] = "8";
  const s = hex.join("");
  return [
    s.slice(0, 8), s.slice(8, 12), s.slice(12, 16), s.slice(16, 20), s.slice(20),
  ].join("-");
}

/**
 * Read the endpoint's declaration by importing it. Bundling to ESM first means
 * the tool never has to care how the source is split up or whether node can
 * strip its types.
 */
async function readDefinition(entry, name) {
  const esm = await bundle(entry, "esm", undefined);
  mkdirSync(join(distDir, "meta"), { recursive: true });
  const metaPath = join(distDir, "meta", name + ".mjs");
  writeFileSync(metaPath, esm, "utf8");
  const module = await import(
    pathToFileURL(metaPath).href + "?t=" + Date.now()
  );
  const main = module.default;
  if (typeof main !== "function" || typeof main.definition !== "object") {
    throw new Error(
      relative(projectRoot, entry) +
        ": default export must be the value returned by defineEndpoint()"
    );
  }
  return main.definition;
}

function banner(name, sourceRelative) {
  return [
    "// @generated by `fo build` from platform/typescript — DO NOT EDIT.",
    "// @ts-nocheck",
    "//",
    "// Source:  " + sourceRelative,
    "// Rebuild: fo build",
    "//",
    "// Bundled with esbuild (es2020) then downlevelled to ES5 by Babel. Edit the",
    "// TypeScript, never this file: the next build overwrites it.",
    "",
  ].join("\n");
}

function footer() {
  // The endpoint's HTTP response body is the script's COMPLETION VALUE, so the
  // file must end with an expression statement (verified 2026-08-13).
  return "\n" + GLOBAL_NAME + ".default();\n";
}

async function buildEndpoint(entry) {
  const fileName = basename(entry, ".ts");
  const definition = await readDefinition(entry, fileName);
  if (definition.name !== fileName) {
    throw new Error(
      relative(projectRoot, entry) +
        ': endpoint name "' +
        definition.name +
        '" must match the file name "' +
        fileName +
        '" — the file name is what `fo sync` pushes'
    );
  }
  const iife = await bundle(entry, "iife", GLOBAL_NAME);
  const code = downlevel(iife, fileName);
  const violations = findRuntimeBanViolations(code);
  if (violations.length > 0) {
    const lines = violations.map(
      (violation) =>
        "  line " +
        violation.line +
        " [" +
        violation.rule +
        "] " +
        violation.message
    );
    throw new Error(
      fileName +
        ": generated bundle breaks IDM runtime rules\n" +
        lines.join("\n")
    );
  }
  const sourceRelative = "typescript/" + relative(projectRoot, entry);
  return {
    name: definition.name,
    entry,
    sourceRelative,
    definition,
    code: banner(definition.name, sourceRelative) + code + footer(),
  };
}

