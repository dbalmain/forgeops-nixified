// The two-step build: type-check -> esbuild bundle -> Babel downlevel -> emit.
//
// WHY TWO TOOLS. esbuild cannot target ES5 at all ("Transforming const to the
// configured target environment (es5) is not supported yet", probed
// 2026-08-13), and Babel has no bundler. So esbuild resolves the module graph
// into one IIFE at ES2020, and Babel downlevels that single file to ES5 with
// `@babel/preset-env`. Babel 8 removed `loose`, so the size/shape savings come
// from `assumptions` instead.
//
// NOTHING IS EMITTED UNLESS EVERY STEP SUCCEEDS FOR EVERY ENDPOINT. A broken
// build must not leave a half-updated bundle for `fo sync` to push.
//
// ON-PREM: output goes to platform/idm/script/ and platform/idm/conf/, which
// the config profile and `fo sync` consume. There is no tenant, so there is no
// push, no conflict detection and no watcher racing a remote — the whole class
// of "someone else overwrote my change" problems simply does not exist here.
//
// Managed file — regenerated by `fo upgrade`.

