async function once() {
  try {
    await run();
    return true;
  } catch (error) {
    console.error(
      "build failed: " + (error instanceof Error ? error.message : error)
    );
    return false;
  }
}

if (typeCheckOnly) {
  // `npm run type-check`. Same function, same program list, no emit.
  //
  // It regenerates managed types FIRST, exactly as the build does. It did not,
  // and the two paths then answered different questions: a changed
  // `managed.json` meant the type-check ran against a stale `src/generated/`
  // while the build regenerated it and emitted against the new one.
  try {
    generateManaged();
    typeCheck();
    process.exit(0);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
} else if (watchMode) {
  const { watch } = await import("node:fs");
  let pending = null;
  let building = false;
  let rerun = false;
  const buildLatest = async () => {
    if (building) {
      rerun = true;
      return;
    }
    building = true;
    try {
      do {
        rerun = false;
        await once();
      } while (rerun);
    } finally {
      building = false;
    }
  };
  const trigger = () => {
    if (pending !== null) {
      clearTimeout(pending);
    }
    pending = setTimeout(() => {
      pending = null;
      void buildLatest();
    }, 250);
  };
  await buildLatest();
  for (const dir of ["src", "framework"]) {
    const target = join(projectRoot, dir);
    if (existsSync(target)) {
      watch(target, { recursive: true }, trigger);
    }
  }
  console.log("watching src/ and framework/ — Ctrl-C to stop");
} else {
  const ok = await once();
  process.exit(ok ? 0 : 1);
}
