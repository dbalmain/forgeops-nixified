/** Publish a complete file in one rename so watchers never see partial data. */
function atomicWrite(path, content) {
  const temporary = join(
    dirname(path),
    "." + basename(path) + "." + process.pid + "." + atomicSequence++ + ".tmp"
  );
  try {
    writeFileSync(temporary, content, "utf8");
    renameSync(temporary, path);
  } finally {
    rmSync(temporary, { force: true });
  }
}

function previouslyOwnedAmScriptNames() {
  if (!existsSync(manifestPath)) {
    return [];
  }
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (!Array.isArray(manifest.amScripts)) {
      return [];
    }
    return manifest.amScripts
      .map((script) => script?.name)
      .filter(
        (name) =>
          typeof name === "string" && /^[A-Za-z0-9._-]+$/.test(name) &&
          name !== "." && name !== ".."
      );
  } catch {
    return [];
  }
}

function retireRemovedAmScripts(previousNames, built) {
  const current = new Set(built.map((script) => script.name));
  for (const name of previousNames) {
    if (!current.has(name)) {
      // Only the local file goes. AM keeps the script until someone deletes
      // it there: an import cannot express a deletion, and silently pruning
      // config from a running realm is not a build's business.
      rmSync(join(amScriptsDir, name + ".json"), { force: true });
    }
  }
}

function previouslyOwnedNames(key) {
  if (!existsSync(manifestPath)) {
    return [];
  }
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (!Array.isArray(manifest[key])) {
      return [];
    }
    return manifest[key]
      .map((entry) => entry?.name)
      .filter(
        (name) =>
          typeof name === "string" && /^[A-Za-z0-9._-]+$/.test(name) &&
          name !== "." && name !== ".."
      );
  } catch {
    return [];
  }
}

function retireRemovedTasks(previousNames, built) {
  const current = new Set(built.map((task) => task.name));
  for (const name of previousNames) {
    if (!current.has(name)) {
      rmSync(join(outputDir, name + ".js"), { force: true });
    }
  }
}

function writeManifest(built, amBuilt, taskBuilt) {
  const manifest = {
    version: 1,
    tasks: taskBuilt.map((task) => ({
      name: task.name,
      source: task.sourceRelative,
      file: "idm/script/" + task.name + ".js",
    })),
    amScripts: amBuilt.map((script) => ({
      name: script.name,
      id: scriptUuid(script.name),
      context: script.definition.context,
      outcomes: script.definition.outcomes,
      source: script.sourceRelative,
      file:
        "amster/config/realms/root/Scripts/" + script.name + ".json",
    })),
    // The record of what this build OWNS, so the next build can retire an
    // endpoint you deleted instead of leaving an orphan script in the pod.
    endpoints: built.map((endpoint) => ({
      name: endpoint.name,
      script: "idm/script/" + endpoint.name + ".js",
      conf: "idm/conf/endpoint-" + endpoint.name + ".json",
      source: endpoint.sourceRelative,
      routes: endpoint.definition.routes.map((route) => ({
        method: route.method,
        path: route.path,
        ...(route.action === undefined ? {} : { action: route.action }),
      })),
    })),
  };
  atomicWrite(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
}

function previouslyOwnedEndpointNames() {
  if (!existsSync(manifestPath)) {
    return [];
  }
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (!Array.isArray(manifest.endpoints)) {
      return [];
    }
    return manifest.endpoints
      .map((endpoint) => endpoint?.name)
      .filter(
        (name) =>
          typeof name === "string" &&
          name !== "." &&
          name !== ".." &&
          /^[A-Za-z0-9._-]+$/.test(name)
      );
  } catch {
    // A malformed generated manifest must not authorize deleting arbitrary
    // workspace files. The new manifest will repair it on this build.
    return [];
  }
}

function retireRemovedEndpoints(previousNames, built) {
  const current = new Set(built.map((endpoint) => endpoint.name));
  for (const name of previousNames) {
    if (!current.has(name)) {
      rmSync(join(outputDir, name + ".js"), { force: true });
      rmSync(join(confDir, "endpoint-" + name + ".json"), { force: true });
      rmSync(join(openapiDir, name + ".openapi.json"), { force: true });
    }
  }
}

function confOutputs(built) {
  return built.map((endpoint) => ({
    path: join(confDir, "endpoint-" + endpoint.name + ".json"),
    content:
      JSON.stringify(
        {
          "//": "@generated by `fo build` from typescript/src/endpoints/" +
            endpoint.name + ".ts — DO NOT EDIT.",
          type: "text/javascript",
          file: endpoint.name + ".js",
        },
        null,
        2
      ) + "\n",
  }));
}

function openApiOutputs(built, toOpenApi) {
  return built.map((endpoint) => {
    const document = toOpenApi(endpoint.definition, {
      title: endpoint.definition.summary ?? endpoint.name,
    });
    return {
      path: join(openapiDir, endpoint.name + ".openapi.json"),
      content: JSON.stringify(document, null, 2) + "\n",
    };
  });
}

/**
 * Regenerate src/generated/managed.ts, if there is a managed.json to read.
 *
 * Runs BEFORE the type-check, because the endpoints being checked import from
 * it. An ABSENT managed.json leaves any existing generated file alone: the
 * file is committed so a fresh clone type-checks without a cluster, and
 * deleting it because nobody has exported yet would break exactly that.
 */
function generateManaged() {
  if (!existsSync(managedJsonPath)) {
    return;
  }
  const managed = JSON.parse(readFileSync(managedJsonPath, "utf8"));
  const content = generateManagedTypes(managed);
  if (existsSync(managedTypesPath) && readFileSync(managedTypesPath, "utf8") === content) {
    return;
  }
  mkdirSync(generatedDir, { recursive: true });
  atomicWrite(managedTypesPath, content);
  const count = Array.isArray(managed.objects) ? managed.objects.length : 0;
  console.log(
    "generated src/generated/managed.ts (" + count + " managed objects)"
  );
}

async function run() {
  generateManaged();
  // Cleared every generation, not just on one-shot builds: `readDefinition`
  // writes one `.mjs` per endpoint here, so a long `--watch` session otherwise
  // accumulates a file per endpoint it has ever seen, including renamed and
  // deleted ones. They are cache-busted on import, so nothing reads a stale one
  // — they just pile up.
  rmSync(join(distDir, "meta"), { recursive: true, force: true });
  const entries = entryPoints();
  const previousNames = previouslyOwnedEndpointNames();
  const previousAmNames = previouslyOwnedAmScriptNames();
  const previousTaskNames = previouslyOwnedNames("tasks");
  // AN ABSENT `src/endpoints` IS NOT AN EMPTY ONE. Retirement deletes every
  // bundle the previous manifest owned, so it must be driven by a project that
  // says "no endpoints", not by a directory that happens not to be there right
  // now — a branch switch, an interrupted move, or a watch tick mid-rename would
  // otherwise wipe the lot and empty the manifest, silently and with exit 0.
  if (!skipTypeCheck) {
    typeCheck();
  }
  if (!existsSync(endpointsDir)) {
    console.log(
      "src/endpoints does not exist — kept the previous manifest and bundles; " +
        "create the directory (even empty) to retire them"
    );
    return;
  }

  // Build everything into memory first: a failure in the last endpoint must
  // not leave the earlier ones half-written on disk.
  const built = [];
  for (const entry of entries) {
    built.push(await buildEndpoint(entry));
  }
  const taskBuilt = [];
  for (const entry of taskEntryPoints()) {
    taskBuilt.push(await buildTask(entry));
  }
  const amBuilt = [];
  for (const entry of amEntryPoints()) {
    amBuilt.push(await buildAmScript(entry));
  }

  const toOpenApi = await loadOpenApiGenerator();

  // Prepare every fallible transformation before publishing any watched
  // output. Publication itself is a sequence of same-directory atomic renames;
  // the manifest is the final commit marker for the generation.
  const openApi = openApiOutputs(built, toOpenApi);
  const confs = confOutputs(built);
  const amScripts = amScriptOutputs(amBuilt);

  mkdirSync(outputDir, { recursive: true });
  mkdirSync(confDir, { recursive: true });
  mkdirSync(openapiDir, { recursive: true });
  if (amScripts.length > 0) {
    mkdirSync(amScriptsDir, { recursive: true });
  }
  for (const endpoint of [...built, ...taskBuilt]) {
    atomicWrite(join(outputDir, endpoint.name + ".js"), endpoint.code);
  }
  for (const output of [...confs, ...openApi, ...amScripts]) {
    atomicWrite(output.path, output.content);
  }
  retireRemovedEndpoints(previousNames, built);
  retireRemovedAmScripts(previousAmNames, amBuilt);
  retireRemovedTasks(previousTaskNames, taskBuilt);
  writeManifest(built, amBuilt, taskBuilt);

  if (built.length === 0) {
    console.log("no endpoints in src/endpoints — retired generated endpoints");
  }

  for (const task of taskBuilt) {
    console.log(
      "built " + task.name + " (IDM task) -> idm/script/" + task.name + ".js"
    );
  }

  for (const script of amBuilt) {
    console.log(
      "built " + script.name + " (AM " + script.definition.context +
        ", " + script.definition.outcomes.length + " outcomes) -> amster/config/realms/root/Scripts/" +
        script.name + ".json"
    );
  }

  for (const endpoint of built) {
    const bytes = Buffer.byteLength(endpoint.code, "utf8");
    console.log(
      "built " +
        endpoint.name +
        " (" +
        endpoint.definition.routes.length +
        " routes, " +
        Math.round(bytes / 1024) +
        " KB) -> idm/script/" +
        endpoint.name +
        ".js + idm/conf/endpoint-" +
        endpoint.name +
        ".json"
    );
  }
}

/** Bundle the framework's OpenAPI generator so this tool can call it. */
async function loadOpenApiGenerator() {
  const source = join(projectRoot, "framework", "openapi.ts");
  const esm = await bundle(source, "esm", undefined);
  mkdirSync(join(distDir, "meta"), { recursive: true });
  const path = join(distDir, "meta", "__openapi.mjs");
  writeFileSync(path, esm, "utf8");
  const module = await import(pathToFileURL(path).href + "?t=" + Date.now());
  return module.toOpenApi;
}

