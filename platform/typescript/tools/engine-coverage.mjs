// What the pinned `lib` actually promises, derived from TypeScript's own
// declaration files.
//
// WHY THIS EXISTS. `framework/engine-surface.json` records what the engines
// were measured to have, and `tests/engine-lib.test.mjs` rejects a lib entry
// that declares something recorded ABSENT. On its own that argument is
// circular: `fo doctor --engines` generates its probes from the keys already
// in the JSON, so a builtin nobody thought to probe can never be discovered,
// and the lib pin ends up describing an engine we only partly measured.
//
// So the required key set is derived from the OTHER side: read the lib files
// the tsconfigs name, enumerate every declaration that carries a runtime
// value, and require each one to appear in the measurement. A builtin the lib
// admits and the probe never checked is then a test failure rather than a
// silence.
//
// This is deliberately not a general TypeScript interpreter. It answers one
// question -- which holder-qualified names do these files promise -- and it
// answers it from the AST rather than from regular expressions, because the
// point is to be exhaustive.
//
// Managed file - regenerated by `fo upgrade`.

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

import { RUNTIME_PROGRAMS } from "./engine-usage.mjs";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

/**
 * The two sets of lib .d.ts files in this package, and why both matter.
 *
 * `tsgo` is what `fo build` type-checks with, so ITS declarations are the ones
 * that decide whether a use of a builtin reaches emission. The `typescript`
 * package is here for its compiler API -- `engine-usage.mjs` needs a program
 * and a checker, and tsgo does not expose one -- and it ships its own copies of
 * the same libs.
 *
 * The two are not the same bytes. Every one of the twelve files this project
 * pins differs between TypeScript 5.9 and the 7.0 native preview. Their
 * DERIVED surfaces agree today, which `tests/engine-lib.test.mjs` asserts, but
 * nothing about the next preview bump guarantees that. So both are digested,
 * and the required set is the union: a builtin either compiler admits has to
 * have been probed.
 */
export const TSGO_LIB_DIR = join(
  dirname(
    require.resolve(
      `@typescript/native-preview-${process.platform}-${process.arch}/package.json`,
    ),
  ),
  "lib",
);
export const TS_LIB_DIR = join(
  dirname(require.resolve("typescript/package.json")),
  "lib",
);

/**
 * Interfaces that describe a SHAPE rather than a runtime object.
 *
 * Everything else is reached through a `declare var`, which is what proves
 * there is something at runtime to probe. These have no global binding, so
 * their members are not builtins and there is nothing to ask the engine.
 */
const STRUCTURAL = new Set([
  // Type-level helpers and call-signature carriers.
  "ArrayLike", "ArrayBufferTypes", "ArrayBufferView", "ConcatArray",
  "CallableFunction", "NewableFunction", "ThisType", "ImportMeta",
  "ImportAssertions", "ImportAttributes", "ImportCallOptions",
  "PropertyDescriptor", "PropertyDescriptorMap", "TypedPropertyDescriptor",
  "TemplateStringsArray", "IArguments", "WeakKeyTypes",
  // Iteration protocol: structural contracts a value may satisfy, not objects.
  "Iterable", "IterableIterator", "Iterator", "IteratorObject",
  "IteratorYieldResult", "IteratorReturnResult", "PromiseLike",
  "ArrayIterator", "MapIterator", "SetIterator", "StringIterator",
  "GeneratorFunction",
  // Results of a call, not globals in their own right.
  "RegExpExecArray", "RegExpMatchArray",
  // `ReadonlyX` is a view over X; its members are X's, already required.
  "ReadonlyArray", "ReadonlyMap", "ReadonlySet",
]);

/**
 * Members that exist on every object, so probing them says nothing about the
 * pin.
 *
 * `length` and `name` used to be here too, and that was wrong: `Function#name`
 * is a real runtime declaration a script can read, and it is exactly the kind
 * of thing an old Rhino might not have. Dropping them meant the census claimed
 * to be exhaustive while silently excluding a member per holder.
 */
const UNINTERESTING = new Set(["prototype", "constructor"]);

function libFile(entry, libDir) {
  return join(libDir, `lib.${entry.toLowerCase()}.d.ts`);
}

/** Strip comments so JSON.parse accepts a tsconfig. */
export function readTsconfig(name) {
  return JSON.parse(readFileSync(join(projectRoot, name), "utf8"));
}

/**
 * The programs whose output runs on a script engine, and the `lib` they share.
 *
 * ASSERTS they share it. Everything here -- the census, the seed, the manifest
 * -- read `tsconfig.json` alone, so a lib entry added to `tsconfig.am.json`
 * would be used by tsgo when it type-checks the PingAM program while coverage
 * went on reporting the measurement fresh. The newly admitted members would be
 * absent from the surface rather than recorded `false`, and absent reads as
 * fine to the use-site check.
 *
 * They are byte-for-byte equal today, which is the project's intent; this is
 * what makes that intent load-bearing instead of a coincidence.
 */
export function sharedRuntimeLibs() {
  // From `RUNTIME_PROGRAMS`, which is documented as THE list, rather than a
  // second copy of it here -- a third runtime program added there would
  // otherwise recreate exactly the coverage drift this function exists to
  // catch.
  const [first, ...rest] = RUNTIME_PROGRAMS.map(({ tsconfig: name }) => ({
    name,
    lib: readTsconfig(name).compilerOptions.lib,
  }));
  for (const other of rest) {
    if (JSON.stringify(other.lib) !== JSON.stringify(first.lib)) {
      throw new Error(
        `${first.name} and ${other.name} no longer pin the same \`lib\`, and ` +
          "everything downstream assumes one shared measurement:\n" +
          `  ${first.name}: ${first.lib.join(", ")}\n` +
          `  ${other.name}: ${other.lib.join(", ")}\n` +
          "Either bring them back into line, or make the census, the seed, " +
          "the manifest and the surface per-program.",
      );
    }
  }
  return first.lib;
}

function memberName(member, sourceFile) {
  if (!member.name) return undefined;
  if (ts.isIdentifier(member.name) || ts.isStringLiteral(member.name)) {
    return member.name.text;
  }
  if (ts.isComputedPropertyName(member.name)) {
    // `[Symbol.iterator]` and friends. The probe indexes with the symbol
    // itself, so keep the source form the surface keys use.
    const text = member.name.expression.getText(sourceFile);
    return /^Symbol\.[A-Za-z]+$/.test(text) ? `[${text}]` : undefined;
  }
  return undefined;
}

/**
 * Every holder-qualified name the given lib entries promise at runtime.
 *
 * Returns keys in `engine-surface.json`'s own vocabulary: `g:Name` for a
 * global binding, `Holder.member` for a static, `Holder#member` for a
 * prototype member.
 */
export function requiredKeys(libEntries, libDir = TSGO_LIB_DIR) {
  const globalType = new Map(); // global name -> the interface it is typed as
  const interfaces = new Map(); // interface name -> Set of member names

  for (const entry of libEntries) {
    const file = libFile(entry, libDir);
    const sourceFile = ts.createSourceFile(
      file,
      readFileSync(file, "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    for (const statement of sourceFile.statements) {
      if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
          if (!ts.isIdentifier(declaration.name)) continue;
          const type =
            declaration.type && ts.isTypeReferenceNode(declaration.type)
              ? declaration.type.typeName.getText(sourceFile)
              : undefined;
          globalType.set(declaration.name.text, type);
        }
      } else if (ts.isFunctionDeclaration(statement) && statement.name) {
        // `declare function parseInt(...)` - a global with no holder.
        globalType.set(statement.name.text, undefined);
      } else if (ts.isInterfaceDeclaration(statement)) {
        const name = statement.name.text;
        let members = interfaces.get(name);
        if (members === undefined) interfaces.set(name, (members = new Set()));
        for (const member of statement.members) {
          const memberIdentifier = memberName(member, sourceFile);
          if (memberIdentifier !== undefined) members.add(memberIdentifier);
        }
      }
    }
  }

  const keys = new Set();
  for (const [name, type] of globalType) {
    keys.add(`g:${name}`);

    // `declare var Math: Math` is a singleton: its interface members are
    // reached as `Math.floor`. `declare var Array: ArrayConstructor` is a
    // constructor: `ArrayConstructor`'s members are statics and `Array`'s are
    // prototype members.
    const constructorInterface = `${name}Constructor`;
    if (type === constructorInterface) {
      for (const member of interfaces.get(constructorInterface) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}.${member}`);
      }
      for (const member of interfaces.get(name) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}#${member}`);
      }
    } else if (type === name) {
      for (const member of interfaces.get(name) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}.${member}`);
      }
    }
  }

  // A structural interface reached no other way contributes nothing; assert it
  // rather than dropping it silently, so a TypeScript release that introduces
  // a new runtime holder is not quietly excluded.
  const unclassified = [...interfaces.keys()].filter(
    (name) =>
      !STRUCTURAL.has(name) &&
      !globalType.has(name) &&
      !(name.endsWith("Constructor") && globalType.has(name.slice(0, -11))),
  );

  return { keys: [...keys].sort(), unclassified: unclassified.sort() };
}

/**
 * A content hash per lib file, plus the TypeScript version.
 *
 * The audit is a measurement of a fixed set of declarations. If TypeScript
 * ships a new member in one of these files, the measurement no longer covers
 * the lib and has to be retaken - this is what makes that loud.
 */
export function libDigests(libEntries, libDir) {
  const digests = {};
  for (const entry of libEntries) {
    digests[entry] = createHash("sha256")
      .update(readFileSync(libFile(entry, libDir)))
      .digest("hex")
      .slice(0, 16);
  }
  return digests;
}

/**
 * Every key EITHER compiler's libs promise.
 *
 * The union rather than tsgo's set alone, so that a native-preview bump which
 * adds a member cannot leave it unprobed while the equality test is being
 * chased down. Seeding and coverage both work from this.
 */
export function requiredKeysUnion(libEntries) {
  const tsgo = requiredKeys(libEntries, TSGO_LIB_DIR);
  const tsc = requiredKeys(libEntries, TS_LIB_DIR);
  return {
    keys: [...new Set([...tsgo.keys, ...tsc.keys])].sort(),
    unclassified: [
      ...new Set([...tsgo.unclassified, ...tsc.unclassified]),
    ].sort(),
  };
}

export function typescriptVersion() {
  return ts.version;
}

export function tsgoVersion() {
  return require("@typescript/native-preview/package.json").version;
}

/**
 * Everything about the measurement that has to hold BEFORE anything is
 * emitted.
 *
 * These four lived only in `tests/engine-lib.test.mjs`, which runs after the
 * build -- and a direct `fo build` never runs it at all. That mattered
 * concretely: after a compiler bump a newly declared builtin is `undefined` in
 * the surface rather than recorded `false`, so the use-site check permits it
 * and the build emits, and only a later test run says the measurement is
 * stale. `fo build` calls this now, so the claim "a compiler bump fails the
 * build" is true rather than aspirational.
 */
export function assertMeasurementCovers(surface, coverage) {
  const libs = sharedRuntimeLibs();

  const tsgo = requiredKeys(libs, TSGO_LIB_DIR);
  const tsc = requiredKeys(libs, TS_LIB_DIR);

  if (tsgo.unclassified.length > 0 || tsc.unclassified.length > 0) {
    throw new Error(
      "interfaces the coverage tool cannot classify as runtime-bearing or " +
        "structural, so it does not know whether to require them: " +
        [...new Set([...tsgo.unclassified, ...tsc.unclassified])].join(", "),
    );
  }

  // The build enforces with tsgo's declarations and this analysis reads
  // typescript's. They are different files; that they promise the same things
  // is a fact with a shelf life.
  const onlyTsgo = tsgo.keys.filter((k) => !tsc.keys.includes(k));
  const onlyTsc = tsc.keys.filter((k) => !tsgo.keys.includes(k));
  if (onlyTsgo.length > 0 || onlyTsc.length > 0) {
    throw new Error(
      "tsgo and typescript no longer declare the same builtins for the " +
        "pinned lib, so the use-site check and the emission gate are no " +
        "longer asking the same question.\n" +
        `  only tsgo: ${onlyTsgo.join(", ") || "(none)"}\n` +
        `  only typescript: ${onlyTsc.join(", ") || "(none)"}`,
    );
  }

  const keys = [...new Set([...tsgo.keys, ...tsc.keys])].sort();
  for (const engine of ["am", "idm"]) {
    const unprobed = keys.filter((k) => !(k in surface[engine]));
    if (unprobed.length > 0) {
      throw new Error(
        `${unprobed.length} builtin(s) the pinned lib declares were never ` +
          `probed on ${engine}: ${unprobed.slice(0, 8).join(", ")}` +
          (unprobed.length > 8 ? ", ..." : "") +
          "\nRun `node tools/engine-coverage.mjs --seed`, then " +
          "`fo doctor --engines --record` against a running stack.",
      );
    }
  }

  const stale = [];
  if (coverage.typescript !== typescriptVersion()) {
    stale.push(`typescript ${coverage.typescript} -> ${typescriptVersion()}`);
  }
  if (coverage.tsgo !== tsgoVersion()) {
    stale.push(`tsgo ${coverage.tsgo} -> ${tsgoVersion()}`);
  }
  if (coverage.requiredKeys !== keys.length) {
    stale.push(`requiredKeys ${coverage.requiredKeys} -> ${keys.length}`);
  }
  const digests = {
    tsgo: libDigests(libs, TSGO_LIB_DIR),
    typescript: libDigests(libs, TS_LIB_DIR),
  };
  // Compared as WHOLE objects, in both directions. Walking only the current
  // entries let a stale extra one survive: drop a lib from the tsconfig and
  // the manifest kept describing a file nobody reads any more, while the build
  // reported the measurement fresh.
  for (const which of ["tsgo", "typescript"]) {
    const recorded = coverage.lib?.[which] ?? {};
    for (const [entry, digest] of Object.entries(digests[which])) {
      if (recorded[entry] !== digest) stale.push(`${which} lib.${entry}`);
    }
    for (const entry of Object.keys(recorded)) {
      if (!(entry in digests[which])) {
        stale.push(`${which} lib.${entry} (recorded, no longer pinned)`);
      }
    }
  }
  if (stale.length > 0) {
    throw new Error(
      "the engine surface was measured against different declaration files " +
        `than the ones in use: ${stale.join(", ")}.\nRe-probe with ` +
        "`fo doctor --engines --record` against a running stack, then " +
        "`node tools/engine-coverage.mjs --manifest`. Do not refresh the " +
        "manifest on its own - the point is that a compiler change cannot be " +
        "waved through without a fresh measurement.",
    );
  }
}

/* --------------------------------------------------------------------- CLI */

/**
 * `node tools/engine-coverage.mjs --seed` adds every required key that
 * `engine-surface.json` does not yet carry, recorded as ABSENT.
 *
 * Absent is the conservative seed on purpose: a key left unmeasured then makes
 * `tests/engine-lib.test.mjs` fail loudly, because the lib declares something
 * the file says the engine lacks. Forgetting the measurement is a red build
 * rather than a quiet assertion of presence.
 *
 * Take the measurement with `fo doctor --engines --record`, which needs a
 * running stack and overwrites these with what the engines actually answered.
 */
async function main() {
  const { writeFileSync } = await import("node:fs");
  const libs = sharedRuntimeLibs();
  const { keys, unclassified } = requiredKeysUnion(libs);
  if (unclassified.length > 0) {
    throw new Error(
      "interfaces this tool cannot classify as runtime-bearing or " +
        "structural: " + unclassified.join(", ") +
        "\nClassify them in STRUCTURAL, or work out which global exposes them.",
    );
  }
  const path = join(projectRoot, "framework", "engine-surface.json");
  const surface = JSON.parse(readFileSync(path, "utf8"));
  let added = 0;
  for (const engine of ["am", "idm"]) {
    for (const key of keys) {
      if (!(key in surface[engine])) {
        surface[engine][key] = false;
        added++;
      }
    }
    surface[engine] = Object.fromEntries(
      Object.entries(surface[engine]).sort(([a], [b]) => (a < b ? -1 : 1)),
    );
  }
  writeFileSync(path, JSON.stringify(surface, null, 2) + "\n", "utf8");
  process.stdout.write(
    `${keys.length} required by the pinned lib; seeded ${added} key/engine ` +
      `pairs as absent. Now run \`fo doctor --engines --record\`.\n`,
  );
}

/**
 * `node tools/engine-coverage.mjs --manifest` freezes what the measurement
 * covered: the TypeScript version, the required key count, and a digest per
 * lib file. Run it AFTER recording, never before.
 */
async function writeManifest() {
  const { writeFileSync } = await import("node:fs");
  const libs = sharedRuntimeLibs();
  const { keys } = requiredKeysUnion(libs);
  const path = join(projectRoot, "framework", "engine-coverage.json");
  const existing = JSON.parse(readFileSync(path, "utf8"));
  writeFileSync(
    path,
    JSON.stringify(
      {
        "//": existing["//"],
        typescript: typescriptVersion(),
        tsgo: tsgoVersion(),
        requiredKeys: keys.length,
        // Both, because the build type-checks with one and this analysis runs
        // on the other. Freezing only the compiler API's copies described lib
        // files the emission gate never reads.
        lib: {
          tsgo: libDigests(libs, TSGO_LIB_DIR),
          typescript: libDigests(libs, TS_LIB_DIR),
        },
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );
  process.stdout.write(
    `manifest frozen: tsgo ${tsgoVersion()}, TypeScript ${typescriptVersion()}, ` +
      `${keys.length} keys, ${libs.length} lib files each.\n`,
  );
}

if (process.argv[2] === "--seed") await main();
if (process.argv[2] === "--manifest") await writeManifest();
