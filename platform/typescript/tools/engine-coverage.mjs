// What the pinned `lib` actually promises, derived from TypeScript's own
// declaration files.
//
// WHY THIS EXISTS. `framework/engine-surface.json` records what the engines
// were measured to have, and `tests/engine-lib.test.mjs` rejects a lib entry
// that declares something recorded ABSENT. On its own that argument is
// circular: `fo doctor --engines` generates its probes from the keys already
// in the JSON, so a builtin nobody thought to probe can never be discovered,
// and the lib pin ends up describing an engine we only partly measured.
//
// So the required key set is derived from the OTHER side: read the lib files
// the tsconfigs name, enumerate every declaration that carries a runtime
// value, and require each one to appear in the measurement. A builtin the lib
// admits and the probe never checked is then a test failure rather than a
// silence.
//
// This is deliberately not a general TypeScript interpreter. It answers one
// question -- which holder-qualified names do these files promise -- and it
// answers it from the AST rather than from regular expressions, because the
// point is to be exhaustive.
//
// Managed file - regenerated by `fo upgrade`.

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Interfaces that describe a SHAPE rather than a runtime object.
 *
 * Everything else is reached through a `declare var`, which is what proves
 * there is something at runtime to probe. These have no global binding, so
 * their members are not builtins and there is nothing to ask the engine.
 */
const STRUCTURAL = new Set([
  // Type-level helpers and call-signature carriers.
  "ArrayLike", "ArrayBufferTypes", "ArrayBufferView", "ConcatArray",
  "CallableFunction", "NewableFunction", "ThisType", "ImportMeta",
  "ImportAssertions", "ImportAttributes", "ImportCallOptions",
  "PropertyDescriptor", "PropertyDescriptorMap", "TypedPropertyDescriptor",
  "TemplateStringsArray", "IArguments", "WeakKeyTypes",
  // Iteration protocol: structural contracts a value may satisfy, not objects.
  "Iterable", "IterableIterator", "Iterator", "IteratorObject",
  "IteratorYieldResult", "IteratorReturnResult", "PromiseLike",
  "ArrayIterator", "MapIterator", "SetIterator", "StringIterator",
  "GeneratorFunction",
  // Results of a call, not globals in their own right.
  "RegExpExecArray", "RegExpMatchArray",
  // `ReadonlyX` is a view over X; its members are X's, already required.
  "ReadonlyArray", "ReadonlyMap", "ReadonlySet",
]);

/**
 * Members that exist on every object or carry no engine capability, so
 * probing them says nothing about the pin.
 */
const UNINTERESTING = new Set(["prototype", "constructor", "length", "name"]);

function libFile(entry) {
  return join(
    projectRoot,
    "node_modules",
    "typescript",
    "lib",
    `lib.${entry.toLowerCase()}.d.ts`,
  );
}

/** Strip comments so JSON.parse accepts a tsconfig. */
export function readTsconfig(name) {
  return JSON.parse(readFileSync(join(projectRoot, name), "utf8"));
}

function memberName(member, sourceFile) {
  if (!member.name) return undefined;
  if (ts.isIdentifier(member.name) || ts.isStringLiteral(member.name)) {
    return member.name.text;
  }
  if (ts.isComputedPropertyName(member.name)) {
    // `[Symbol.iterator]` and friends. The probe indexes with the symbol
    // itself, so keep the source form the surface keys use.
    const text = member.name.expression.getText(sourceFile);
    return /^Symbol\.[A-Za-z]+$/.test(text) ? `[${text}]` : undefined;
  }
  return undefined;
}

/**
 * Every holder-qualified name the given lib entries promise at runtime.
 *
 * Returns keys in `engine-surface.json`'s own vocabulary: `g:Name` for a
 * global binding, `Holder.member` for a static, `Holder#member` for a
 * prototype member.
 */
export function requiredKeys(libEntries) {
  const globalType = new Map(); // global name -> the interface it is typed as
  const interfaces = new Map(); // interface name -> Set of member names

  for (const entry of libEntries) {
    const file = libFile(entry);
    const sourceFile = ts.createSourceFile(
      file,
      readFileSync(file, "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    for (const statement of sourceFile.statements) {
      if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
          if (!ts.isIdentifier(declaration.name)) continue;
          const type =
            declaration.type && ts.isTypeReferenceNode(declaration.type)
              ? declaration.type.typeName.getText(sourceFile)
              : undefined;
          globalType.set(declaration.name.text, type);
        }
      } else if (ts.isFunctionDeclaration(statement) && statement.name) {
        // `declare function parseInt(...)` - a global with no holder.
        globalType.set(statement.name.text, undefined);
      } else if (ts.isInterfaceDeclaration(statement)) {
        const name = statement.name.text;
        let members = interfaces.get(name);
        if (members === undefined) interfaces.set(name, (members = new Set()));
        for (const member of statement.members) {
          const memberIdentifier = memberName(member, sourceFile);
          if (memberIdentifier !== undefined) members.add(memberIdentifier);
        }
      }
    }
  }

  const keys = new Set();
  for (const [name, type] of globalType) {
    keys.add(`g:${name}`);

    // `declare var Math: Math` is a singleton: its interface members are
    // reached as `Math.floor`. `declare var Array: ArrayConstructor` is a
    // constructor: `ArrayConstructor`'s members are statics and `Array`'s are
    // prototype members.
    const constructorInterface = `${name}Constructor`;
    if (type === constructorInterface) {
      for (const member of interfaces.get(constructorInterface) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}.${member}`);
      }
      for (const member of interfaces.get(name) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}#${member}`);
      }
    } else if (type === name) {
      for (const member of interfaces.get(name) ?? []) {
        if (!UNINTERESTING.has(member)) keys.add(`${name}.${member}`);
      }
    }
  }

  // A structural interface reached no other way contributes nothing; assert it
  // rather than dropping it silently, so a TypeScript release that introduces
  // a new runtime holder is not quietly excluded.
  const unclassified = [...interfaces.keys()].filter(
    (name) =>
      !STRUCTURAL.has(name) &&
      !globalType.has(name) &&
      !(name.endsWith("Constructor") && globalType.has(name.slice(0, -11))),
  );

  return { keys: [...keys].sort(), unclassified: unclassified.sort() };
}

/**
 * A content hash per lib file, plus the TypeScript version.
 *
 * The audit is a measurement of a fixed set of declarations. If TypeScript
 * ships a new member in one of these files, the measurement no longer covers
 * the lib and has to be retaken - this is what makes that loud.
 */
export function libDigests(libEntries) {
  const digests = {};
  for (const entry of libEntries) {
    digests[entry] = createHash("sha256")
      .update(readFileSync(libFile(entry)))
      .digest("hex")
      .slice(0, 16);
  }
  return digests;
}

export function typescriptVersion() {
  return ts.version;
}

/* --------------------------------------------------------------------- CLI */

/**
 * `node tools/engine-coverage.mjs --seed` adds every required key that
 * `engine-surface.json` does not yet carry, recorded as ABSENT.
 *
 * Absent is the conservative seed on purpose: a key left unmeasured then makes
 * `tests/engine-lib.test.mjs` fail loudly, because the lib declares something
 * the file says the engine lacks. Forgetting the measurement is a red build
 * rather than a quiet assertion of presence.
 *
 * Take the measurement with `fo doctor --engines --record`, which needs a
 * running stack and overwrites these with what the engines actually answered.
 */
async function main() {
  const { writeFileSync } = await import("node:fs");
  const libs = readTsconfig("tsconfig.json").compilerOptions.lib;
  const { keys, unclassified } = requiredKeys(libs);
  if (unclassified.length > 0) {
    throw new Error(
      "interfaces this tool cannot classify as runtime-bearing or " +
        "structural: " + unclassified.join(", ") +
        "\nClassify them in STRUCTURAL, or work out which global exposes them.",
    );
  }
  const path = join(projectRoot, "framework", "engine-surface.json");
  const surface = JSON.parse(readFileSync(path, "utf8"));
  let added = 0;
  for (const engine of ["am", "idm"]) {
    for (const key of keys) {
      if (!(key in surface[engine])) {
        surface[engine][key] = false;
        added++;
      }
    }
    surface[engine] = Object.fromEntries(
      Object.entries(surface[engine]).sort(([a], [b]) => (a < b ? -1 : 1)),
    );
  }
  writeFileSync(path, JSON.stringify(surface, null, 2) + "\n", "utf8");
  process.stdout.write(
    `${keys.length} required by the pinned lib; seeded ${added} key/engine ` +
      `pairs as absent. Now run \`fo doctor --engines --record\`.\n`,
  );
}

/**
 * `node tools/engine-coverage.mjs --manifest` freezes what the measurement
 * covered: the TypeScript version, the required key count, and a digest per
 * lib file. Run it AFTER recording, never before.
 */
async function writeManifest() {
  const { writeFileSync } = await import("node:fs");
  const libs = readTsconfig("tsconfig.json").compilerOptions.lib;
  const { keys } = requiredKeys(libs);
  const path = join(projectRoot, "framework", "engine-coverage.json");
  const existing = JSON.parse(readFileSync(path, "utf8"));
  writeFileSync(
    path,
    JSON.stringify(
      {
        "//": existing["//"],
        typescript: typescriptVersion(),
        requiredKeys: keys.length,
        lib: libDigests(libs),
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );
  process.stdout.write(
    `manifest frozen: TypeScript ${typescriptVersion()}, ${keys.length} keys, ` +
      `${libs.length} lib files.\n`,
  );
}

if (process.argv[2] === "--seed") await main();
if (process.argv[2] === "--manifest") await writeManifest();
